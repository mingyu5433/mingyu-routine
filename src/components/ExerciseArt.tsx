export function ExerciseArt({ art, className = '' }: { art: ArtKey; className?: string }) {
  const s = ART[art];
  return (
    <svg viewBox="0 0 120 80" className={className} fill="none" stroke="currentColor" strokeWidth={3.2}
      strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
      {s.r?.map(([x, y, w, h], i) => <rect key={`r${i}`} x={x} y={y} width={w} height={h} rx={2} strokeWidth={2.4} opacity={0.55} />)}
      {s.l?.map((p, i) => {
        const pts = p.reduce<string[]>((acc, v, k) => (k % 2 ? (acc[acc.length - 1] += `,${v}`, acc) : [...acc, `${v}`]), []);
        const isFloor = p.length === 4 && p[1] === p[3] && p[2] - p[0] > 80;
        const isWall = p.length === 4 && p[0] === p[2] && p[3] - p[1] > 60;
        return <polyline key={`l${i}`} points={pts.join(' ')} opacity={isFloor || isWall ? 0.3 : 1} strokeWidth={isFloor || isWall ? 2 : 3.2} />;
      })}
      {s.c?.map(([x, y, r], i) => <circle key={`c${i}`} cx={x} cy={y} r={r} />)}
      {s.a?.map(([x1, y1, x2, y2], i) => {
        const up = y2 < y1;
        return (
          <g key={`a${i}`} className="text-primary" stroke="currentColor" strokeWidth={2.4}>
            <line x1={x1} y1={y1} x2={x2} y2={y2} />
            <polyline points={`${x2 - 4},${up ? y2 + 5 : y2 - 5} ${x2},${y2} ${x2 + 4},${up ? y2 + 5 : y2 - 5}`} />
          </g>
        );
      })}
    </svg>
  );
}
